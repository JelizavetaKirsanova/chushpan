// Isolated loopback TLS test. Certificate errors are ignored only for this ephemeral test CA.
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
const {chromium}=await import(process.argv[2]);
const output=process.argv[3],url=process.argv[4];
const browser=await chromium.launch({headless:true,args:['--mute-audio']});
try {
  const desktop=await browser.newPage({viewport:{width:1440,height:1000}});
  await desktop.goto('http://127.0.0.1:8878');
  await desktop.locator('.workspace-nav [data-view=memory]').click();
  await desktop.getByRole('button',{name:'+ Воспоминание',exact:true}).click();
  await desktop.getByLabel('Что запомнить',{exact:true}).fill('TEST: selective mobile memory');
  await desktop.locator('dialog').getByRole('button',{name:'Сохранить',exact:true}).click();
  await desktop.locator('.memory-open').filter({hasText:'TEST: selective'}).waitFor();
  await desktop.locator('.workspace-nav [data-view=my-devices]').click();
  const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:390,height:844}});
  const mobile=await context.newPage();const errors=[];mobile.on('pageerror',error=>errors.push(error.message));
  await mobile.goto(url);
  await mobile.getByLabel('Имя устройства',{exact:true}).fill('TEST browser iPhone');
  await mobile.getByRole('button',{name:'Подтвердить на этом устройстве',exact:true}).click();
  await mobile.locator('#pair-code').filter({hasText:/^\d{6}$/}).waitFor();
  assert.equal(await mobile.evaluate(()=>keys.privateKey.extractable),false);
  await mobile.screenshot({path:output+'/mobile-pairing.png',fullPage:true});
  await desktop.locator('#module-my-devices').getByRole('button',{name:'Код совпадает — подключить',exact:true}).click();
  await desktop.locator('#module-my-devices').getByRole('button',{name:'Настроить',exact:true}).first().click();
  await desktop.getByLabel('Текстовый чат с настроенной моделью',{exact:true}).check();
  await desktop.getByLabel('Подтверждённая общая память',{exact:true}).check();
  await desktop.getByRole('button',{name:'Сохранить разрешения',exact:true}).click();
  await mobile.evaluate(()=>poll());
  await mobile.locator('#workspace').waitFor({state:'visible'});
  await mobile.getByLabel('Сообщение',{exact:true}).fill('TEST request over signed TLS');
  await mobile.getByRole('button',{name:'Отправить',exact:true}).click();
  await mobile.locator('#messages .assistant').filter({hasText:'TEST REPLY'}).waitFor({timeout:30000});
  await mobile.screenshot({path:output+'/mobile-chat.png',fullPage:true});
  await mobile.reload();
  await mobile.locator('#workspace').waitFor({state:'visible'});
  assert.equal(await mobile.evaluate(()=>keys.privateKey.extractable),false);
  await mobile.getByRole('button',{name:'Данные',exact:true}).click();
  await mobile.getByRole('button',{name:'Синхронизировать',exact:true}).click();
  await mobile.locator('#sync-data').getByText('TEST: selective mobile memory',{exact:true}).waitFor();
  await mobile.screenshot({path:output+'/mobile-sync.png',fullPage:true});
  await mobile.getByRole('button',{name:'Чат',exact:true}).click();
  await context.setOffline(true);await mobile.evaluate(()=>poll());
  await mobile.getByLabel('Сообщение',{exact:true}).fill('TEST queued with consent');
  await mobile.getByRole('button',{name:'Отправить',exact:true}).click();
  assert.match(await mobile.locator('#notice').innerText(),/не отправлена/);
  await mobile.getByLabel('Сохранить текстовый запрос до восстановления связи (до 60 секунд)',{exact:true}).check();
  await mobile.getByRole('button',{name:'Отправить',exact:true}).click();
  await mobile.locator('#notice').filter({hasText:/в очереди/}).waitFor();
  assert.match(await mobile.locator('#notice').innerText(),/в очереди/);
  await context.setOffline(false);await mobile.evaluate(()=>poll());
  await mobile.locator('#messages .assistant').filter({hasText:'TEST REPLY'}).waitFor({timeout:30000});
  await desktop.locator('#module-my-devices').getByRole('button',{name:'Настроить',exact:true}).first().click();
  desktop.once('dialog',dialog=>dialog.accept());
  await desktop.getByRole('button',{name:'Отозвать доверие',exact:true}).click();
  await mobile.evaluate(()=>poll());
  assert.match(await mobile.locator('#connection').innerText(),/Нет подтверждённой связи/);
  assert.deepEqual(errors,[]);
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await writeFile(output+'/companion-verification.json',JSON.stringify({status:'passed',transport:'loopback HTTPS with test CA only',identity:'non-extractable P-256 key persisted in IndexedDB',flows:['mutual pairing','signed chat','reload and reconnect','selective memory copy','offline queue consent','revocation'],errors},null,2));
  process.stdout.write('Passed: mobile WebCrypto → HTTPS → Mac approval → signed chat, selective sync, offline queue, revoke.\n');
}finally{await browser.close();}
